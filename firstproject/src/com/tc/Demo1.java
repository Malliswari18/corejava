package com.tc;

public class Demo1 {
	public static void main(String[] args) {
		double a=25.5;
		int b=(int)a;
		System.out.println(a);
		System.out.println(b);
		System.out.println();
		float c=15.6f;
		short d=(short)c;
		System.out.println(c);
		System.out.println(d);
		System.out.println();
		float f=23.7f;
		byte g=(byte)f;
		System.out.println(f);
		System.out.println(g);
	}

}
